    def get_best_schedule(self, hof: tools.HallOfFame) -> Dict:
        """
        Decode the best chromosome and return the full schedule result dict.

        Runs ``calculateSerialScheduleWithResources`` with the best activity
        list ordering so the ``Pert`` object is left in the state of the best
        found schedule (Gantt chart, constrained chain, etc. are accessible).

        Parameters
        ----------
        hof : HallOfFame
            As returned by ``run()``.

        Returns
        -------
        dict
            Same keys as ``calculateSerialScheduleWithResources``:
            ``scheduled_duration``, ``cpm_duration``, ``delay_hours``,
            ``n_activities``, ``n_completed``, ``priority_rule``.
        """
        ordered_acts = self._chromosome_to_activities(hof[0])
        return self.pert.calculateSerialScheduleWithResources(_ordered=ordered_acts)

    def get_best_activity_list(self, hof: tools.HallOfFame) -> List[str]:
        """
        Return the best chromosome as a human-readable list of task IDs.

        Parameters
        ----------
        hof : HallOfFame
            As returned by ``run()``.

        Returns
        -------
        list of str
            Activity names in the best scheduling order.
        """
        return [self._activities[i].returnName() for i in hof[0]]

    def get_convergence_summary(self, log: tools.Logbook) -> Dict:
        """
        Extract a concise convergence summary from the logbook.

        Parameters
        ----------
        log : Logbook
            As returned by ``run()``.

        Returns
        -------
        dict with keys:
            ``n_gen``, ``best_duration``, ``initial_best``, ``improvement``,
            ``final_avg``, ``final_std``.
        """
        gen0 = log[0]
        final = log[-1]
        return {
            'n_gen': len(log) - 1,
            'best_duration': final['min'],
            'initial_best': gen0['min'],
            'improvement': gen0['min'] - final['min'],
            'final_avg': final['avg'],
            'final_std': final['std'],
        }
