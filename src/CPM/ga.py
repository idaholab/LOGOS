"""
ga.py — Genetic Algorithm for Resource-Constrained Project Scheduling (RCPSP)

Implements the Activity List representation and one-point crossover operator
from Hartmann (1998) / Kolisch & Hartmann (1999), using DEAP as the GA engine.

References
----------
Kolisch, R. and Hartmann, S. (1999). Heuristic Algorithms for Solving the
Resource-Constrained Project Scheduling Problem: Classification and
Computational Analysis. In J. Weglarz (ed.), Project Scheduling: Recent
Models, Algorithms and Applications, 147-178. Kluwer.

Hartmann, S. (1998). A competitive genetic algorithm for resource-constrained
project scheduling. Naval Research Logistics.

Chromosome representation
-------------------------
A **precedence-feasible activity list**

    λ = [i₀, i₁, ..., i_{N-1}]

where each element is the index of an activity in ``pert.forwardDict`` (i.e.
``pert.forwardDict.keys()`` enumerated once at construction time).  Activity
at position g must have all its predecessors at earlier positions (precedence
feasibility).

``pert.priority_calculation()`` with ``reorder_by_dependencies()`` always
produces precedence-feasible orderings, so all chromosomes derived from named
priority rules are valid.  Random chromosomes are generated by calling the
same pipeline with ``priority_rule='random'``.

Decoding (fitness evaluation)
------------------------------
A chromosome is decoded by passing the corresponding ordered list of
``Activity`` objects to ``pert.calculateSerialScheduleWithResources()`` via
the ``_ordered`` keyword added in this release.  Fitness =
``out['scheduled_duration'] - 2`` (strips dummy start/end overhead).

Initial population
------------------
One individual per entry in ``PRIORITY_RULES`` is seeded using
``priority_calculation`` to build the ordering.  The schedule durations from
both serial SGS (``calculateSerialScheduleWithResources``) and parallel SGS
(``calculateScheduleWithResources(sgs='max_use_res_ranked')``) are recorded
for the same priority rule for benchmarking purposes only.  Remaining
population slots are filled with random precedence-feasible permutations.

Crossover — Hartmann (1998) one-point crossover for activity lists
------------------------------------------------------------------
Given mother λᴹ and father λᶠ and a random cut point q (1 ≤ q < N):

1. The first q positions of the child are taken directly from the mother.
2. The remaining N-q positions are filled by scanning the father from left
   to right and appending each activity not yet present in the child.

Hartmann (1998) proves that a child produced this way from two
precedence-feasible parents is itself precedence-feasible.

Two children are produced symmetrically (roles of mother and father swapped).

Mutation — swap mutation with topological repair
-------------------------------------------------
A single individual is mutated by:

1. Picking two random distinct positions i and j.
2. Swapping the activities at those positions (potentially violating
   precedence constraints).
3. Reconstructing ``(Activity, rank)`` pairs from the perturbed ordering
   (rank = position index).
4. Calling ``pert.reorder_by_dependencies(ranked, pert.forwardDict)`` which
   performs a lexicographic topological sort that preserves the perturbed
   order as closely as possible while restoring precedence feasibility.
5. Mapping the repaired activity sequence back to the index chromosome.

This keeps the swap when it is already feasible and makes the minimum
necessary adjustment when it is not, so the mutation injects genuine
diversity while always producing a valid chromosome.

Requirements
------------
    pip install deap
"""

from __future__ import annotations

import logging
import random
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

try:
    from deap import algorithms, base, creator, tools
except ImportError as _deap_err:
    raise ImportError(
        "DEAP is required by ga.py. Install it with:  pip install deap"
    ) from _deap_err

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Priority rules used to seed the initial population.
# Must match rules accepted by Pert.priority_calculation().
# ---------------------------------------------------------------------------
PRIORITY_RULES: List[str] = [
    'es', 'ef', 'ls', 'lf', 'duration', 'random',
    'mts', 'mtp', 'grpw', 'grd', 'rr', 'avgrr',
    'maxrr', 'minrr', 'irsm', 'wcs', 'acs',
    'mehh_8000_b', 'mehh_3375_b', 'mehh_1000_b', 'mehh_125_b', 'gphh_b',
]


class RCPSPGeneticAlgorithm:
    """
    Genetic Algorithm optimiser for RCPSP using the Activity List
    representation and the serial SGS decoder (Hartmann 1998).

    Parameters
    ----------
    pert : Pert
        A fully initialised ``Pert`` object.  ``generateInfo()`` must have
        been called so that ``infoDict`` entries are populated.
    pop_size : int
        Total population size.  The first ``min(len(PRIORITY_RULES), pop_size)``
        slots are seeded from named priority rules; the rest are random
        precedence-feasible permutations.
    n_gen : int
        Number of GA generations.
    cxpb : float
        Probability of applying crossover to a selected pair of parents.
    seed : int
        RNG seed for reproducibility.
    n_random : int
        Number of additional random precedence-feasible reference orderings
        to include in the consensus library.
    hof_size : int
        Number of elite individuals kept in the Hall of Fame across all
        generations.
    verbose : bool
        Print generation statistics and seeding table to stdout.
    crossover : str
        Crossover operator to use.  Choices:

        * ``'one_point'``    — Hartmann (1998) one-point crossover
        * ``'two_point'``    — two-point crossover (default)
        * ``'uniform_order'`` — uniform order-preserving crossover (UOX)
    mutation : str
        Mutation operator to use.  Choices:

        * ``'swap'``              — random swap with topological repair
        * ``'adjacent_swap'``     — adjacent-swap with feasibility check (default)
        * ``'insertion_window'``  — precedence-window insertion
        * ``'consensus_reorder'`` — local reorder guided by consensus references
    """

    # DEAP creator type names (module-level singletons; guarded against
    # re-creation across multiple instantiations in the same process).
    _FITNESS_CLS = "FitnessMinRCPSP"
    _INDIVIDUAL_CLS = "IndividualRCPSP"

    # Maps accepted string names to the corresponding bound methods.
    # Populated after the method definitions — see bottom of class body.
    _CROSSOVER_METHODS: Dict[str, str] = {
        'one_point':    '_crossover_one_point',
        'two_point':    '_crossover_two_point',
        'uniform_order': '_crossover_uniform_order',
    }
    _MUTATION_METHODS: Dict[str, str] = {
        'swap':             '_mutate_swap',
        'adjacent_swap':    '_mutate_adjacent_swap',
        'insertion_window': '_mutate_insertion_window',
        'consensus_reorder': '_mutate_consensus_reorder',
    }

    def __init__(
        self,
        pert,
        pop_size: int = 50,
        n_gen: int = 100,
        cxpb: float = 0.7,
        mutpb: float = 0.1,
        seed: int = 42,
        n_random: int = 8,
        hof_size: int = 5,
        verbose: bool = True,
        crossover: str = 'two_point',
        mutation: str = 'adjacent_swap',
    ) -> None:
        if crossover not in self._CROSSOVER_METHODS:
            raise ValueError(
                f"Unknown crossover '{crossover}'. "
                f"Choose from: {list(self._CROSSOVER_METHODS)}"
            )
        if mutation not in self._MUTATION_METHODS:
            raise ValueError(
                f"Unknown mutation '{mutation}'. "
                f"Choose from: {list(self._MUTATION_METHODS)}"
            )
        if pop_size <= 0:
            raise ValueError("pop_size must be positive.")
        if n_gen < 0:
            raise ValueError("n_gen must be non-negative.")
        if not 0.0 <= cxpb <= 1.0:
            raise ValueError("cxpb must be in [0, 1].")
        if not 0.0 <= mutpb <= 1.0:
            raise ValueError("mutpb must be in [0, 1].")
        if n_random < 0:
            raise ValueError("n_random must be non-negative.")
        if hof_size <= 0:
            raise ValueError("hof_size must be positive.")

        self.pert = pert
        self.pop_size = pop_size
        self.n_gen = n_gen
        self.cxpb = cxpb
        self.mutpb = mutpb
        self.n_random = n_random
        self.hof_size = hof_size
        self.verbose = verbose
        self.crossover = crossover
        self.mutation = mutation

        random.seed(seed)
        np.random.seed(seed)

        # Fixed enumeration of all activities; order matches forwardDict
        self._activities: List[Any] = list(pert.forwardDict.keys())
        self._n: int = len(self._activities)
        self._act_to_idx: Dict[Any, int] = {
            a: i for i, a in enumerate(self._activities)
        }
        self._consensus_library: List[List[int]] = []
        self._consensus_position_maps: List[Dict[int, int]] = []

        self._setup_deap()
        self._build_consensus_library(self.n_random)

    # ---------------------------------------------------------------------- #
    # DEAP registration                                                        #
    # ---------------------------------------------------------------------- #

    def _setup_deap(self) -> None:
        """Register DEAP fitness / individual types and genetic operators."""
        if not hasattr(creator, self._FITNESS_CLS):
            creator.create(self._FITNESS_CLS, base.Fitness, weights=(-1.0,))
        if not hasattr(creator, self._INDIVIDUAL_CLS):
            creator.create(
                self._INDIVIDUAL_CLS,
                list,
                fitness=getattr(creator, self._FITNESS_CLS),
            )
        self._Ind = getattr(creator, self._INDIVIDUAL_CLS)

        cx_fn = getattr(self, self._CROSSOVER_METHODS[self.crossover])
        mut_fn = getattr(self, self._MUTATION_METHODS[self.mutation])

        tb = base.Toolbox()
        tb.register("evaluate", self._evaluate)
        tb.register("mate", cx_fn)
        tb.register("mutate", mut_fn)
        tb.register("select", tools.selTournament, tournsize=3)
        self.toolbox = tb

    # ---------------------------------------------------------------------- #
    # Chromosome ↔ activity list conversion                                    #
    # ---------------------------------------------------------------------- #

    def _rule_to_chromosome(self, rule: str) -> List[int]:
        """
        Build a precedence-feasible activity list chromosome from a priority rule.

        Calls ``pert.priority_calculation(all_acts, priority_rule=rule)``.
        ``priority_calculation`` applies ``reorder_by_dependencies`` internally,
        which performs a lexicographic topological sort that guarantees
        precedence feasibility.

        The chromosome is a list of integer indices into ``self._activities``.

        Parameters
        ----------
        rule : str
            Any priority rule accepted by ``Pert.priority_calculation()``.
            Use ``'random'`` to obtain a random precedence-feasible permutation.

        Returns
        -------
        list of int, length ``self._n``
        """
        all_acts = list(self.pert.forwardDict.keys())
        raw = self.pert.priority_calculation(all_acts, priority_rule=rule)

        # priority_calculation returns [(Activity, raw_val, inv_rank), ...] for
        # all rules (including 'random' after normalize_tuples + reorder).
        # Extract the ordered Activity list.
        if raw and isinstance(raw[0], tuple):
            ordered_acts = [a for (a, _, _) in raw]
        else:
            ordered_acts = list(raw)  # fallback (shouldn't occur)

        return [self._act_to_idx[a] for a in ordered_acts]

    def _chromosome_to_activities(self, chromosome: List[int]) -> List[Any]:
        """Convert an index-list chromosome to an ordered list of Activity objects."""
        return [self._activities[i] for i in chromosome]

    def _repair_chromosome(self, chromosome: List[int]) -> List[int]:
        """
        Restore precedence feasibility while preserving the perturbed order
        as closely as possible.
        """
        acts = self._chromosome_to_activities(chromosome)
        ranked = [(a, pos) for pos, a in enumerate(acts)]
        repaired = self.pert.reorder_by_dependencies(ranked, self.pert.forwardDict)
        return [self._act_to_idx[a] for a, _ in repaired]

    def _build_consensus_library(self, n_random: int) -> None:
        """
        Build a small library of precedence-feasible reference orderings used
        by consensus-guided mutation.
        """
        references: List[List[int]] = []
        seen: set[Tuple[int, ...]] = set()

        for rule in PRIORITY_RULES:
            try:
                chromosome = self._rule_to_chromosome(rule)
            except Exception as exc:  # noqa: BLE001
                logger.debug(
                    "Skipping rule '%s' in consensus library construction: %s",
                    rule,
                    exc,
                )
                continue
            key = tuple(chromosome)
            if key not in seen:
                references.append(chromosome)
                seen.add(key)

        for _ in range(n_random):
            chromosome = self._rule_to_chromosome('random')
            key = tuple(chromosome)
            if key not in seen:
                references.append(chromosome)
                seen.add(key)

        self._consensus_library = references
        self._consensus_position_maps = [
            {gene: pos for pos, gene in enumerate(chromosome)}
            for chromosome in references
        ]

    # ---------------------------------------------------------------------- #
    # Initial population                                                       #
    # ---------------------------------------------------------------------- #

    def generate_initial_population(self) -> List[Any]:
        """
        Build the initial population.

        For each rule in ``PRIORITY_RULES`` (up to ``pop_size``):

        1. Derive a precedence-feasible activity list chromosome via
           ``_rule_to_chromosome(rule)``.
        2. Record the schedule duration produced by the same priority rule
           under *both* SGS variants for benchmarking:

           - Serial SGS: ``calculateSerialScheduleWithResources(priority_rule=rule)``
           - Parallel SGS: ``calculateScheduleWithResources(sgs='max_use_res_ranked',
             priority_rule=rule)``

        Remaining slots are filled with random precedence-feasible permutations
        obtained by calling ``_rule_to_chromosome('random')``, which applies
        ``priority_calculation`` with ``priority_rule='random'`` and thereby
        uses ``reorder_by_dependencies`` to enforce topological feasibility.

        ``pert.priorities`` is cleared to ``None`` before each named-rule SGS
        call so that any previously injected external priorities do not
        interfere.

        Returns
        -------
        list of IndividualRCPSP
        """
        population: List[Any] = []
        seed_info: Dict[str, Dict[str, float]] = {}

        for rule in PRIORITY_RULES:
            if len(population) >= self.pop_size:
                break
            try:
                # --- chromosome from rule ordering ---
                chromosome = self._rule_to_chromosome(rule)
                population.append(self._Ind(chromosome))

                # --- serial SGS duration (informational) ---
                self.pert.priorities = None
                serial_out = self.pert.calculateSerialScheduleWithResources(
                    priority_rule=rule
                )

                # --- parallel SGS duration (informational) ---
                self.pert.priorities = None
                parallel_out = self.pert.calculateScheduleWithResources(
                    sgs='max_use_res_ranked', priority_rule=rule
                )

                seed_info[rule] = {
                    'serial': serial_out['scheduled_duration'] - 2,
                    'parallel': parallel_out['scheduled_duration'] - 2,
                }

            except Exception as exc:  # noqa: BLE001
                logger.warning(
                    "Skipping rule '%s' during population seeding: %s", rule, exc
                )

        # --- fill remaining slots with random precedence-feasible permutations ---
        n_random = 0
        random_failures = 0
        max_random_failures = max(10, self.pop_size * 2)
        while len(population) < self.pop_size:
            try:
                chromosome = self._rule_to_chromosome('random')
            except Exception as exc:  # noqa: BLE001
                random_failures += 1
                logger.warning(
                    "Random chromosome generation failed during population "
                    "seeding (%d/%d): %s",
                    random_failures,
                    max_random_failures,
                    exc,
                )
                if random_failures >= max_random_failures:
                    break
                continue
            population.append(self._Ind(chromosome))
            n_random += 1

        if not population:
            raise RuntimeError(
                "Failed to generate any valid individuals for the initial population."
            )

        if seed_info and self.verbose:
            all_dur = [v for info in seed_info.values() for v in info.values()]
            print(
                f"\nInitial population: {len(seed_info)} rule-seeded + "
                f"{n_random} random  |  best seeded = {min(all_dur):.2f} h\n"
            )
            print(f"  {'Rule':<22} {'Serial (h)':>12} {'Parallel (h)':>14}")
            print("  " + "-" * 50)
            for r, info in seed_info.items():
                print(
                    f"  {r:<22} {info['serial']:>12.2f} {info['parallel']:>14.2f}"
                )
            print()
        elif seed_info:
            all_dur = [v for info in seed_info.values() for v in info.values()]
            logger.info(
                "Initial population: %d rule-seeded + %d random | "
                "best seeded duration = %.2f h",
                len(seed_info),
                n_random,
                min(all_dur),
            )

        return population

    # ---------------------------------------------------------------------- #
    # Fitness evaluation                                                       #
    # ---------------------------------------------------------------------- #

    def _evaluate(self, individual: List[int]) -> Tuple[float, ...]:
        """
        Decode an activity list chromosome and evaluate fitness using the
        Serial SGS.

        The chromosome (index permutation) is converted to an ordered list of
        ``Activity`` objects and passed to
        ``pert.calculateSerialScheduleWithResources(_ordered=...)`` which
        schedules each activity at the earliest feasible time consistent with
        the given ordering, precedence constraints, and resource/equipment/
        location capacity.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.

        Returns
        -------
        tuple of float
            ``(scheduled_duration - 2,)`` — single-objective minimisation.
        """
        ordered_acts = self._chromosome_to_activities(individual)
        out = self.pert.calculateSerialScheduleWithResources(_ordered=ordered_acts)
        return (out['scheduled_duration'] - 2,)

    # ---------------------------------------------------------------------- #
    # Crossover — Hartmann (1998) one-point crossover for activity lists       #
    # ---------------------------------------------------------------------- #

    @staticmethod
    def _crossover_one_point(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        One-point crossover for precedence-feasible activity lists.

        Algorithm (Hartmann 1998, Section 4.2.1):
        ------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw a random cut point q with 1 ≤ q < N.
        2. Child 1 inherits positions 1..q from the mother.
        3. The remaining positions of Child 1 are filled by scanning the
           father left-to-right and appending each activity not already
           present in the child.
        4. Child 2 is built symmetrically (mother and father roles swapped).

        Hartmann (1998) proves that when both parents are precedence-feasible
        the child produced by this operator is also precedence-feasible,
        because:
        - The prefix is directly taken from a feasible list ⇒ each of those
          activities has all its predecessors before it.
        - The suffix preserves the relative order of the father, which is
          itself feasible, and only activities whose predecessors are already
          covered by the prefix are pulled in from that relative order first.

        Example (paper, p. 11, q = 3):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            λᶜ = [1, 3, 2, 4, 6, 5]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 2:
            return ind1, ind2

        q = random.randint(1, n - 1)

        # Save originals so Child 2 reads the unmodified first parent.
        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: prefix from ind1 (mother), suffix from ind2 (father) ---
        prefix1 = list(orig1[:q])
        taken1 = set(prefix1)
        suffix1 = [gene for gene in orig2 if gene not in taken1]
        ind1[:] = prefix1 + suffix1

        # --- Child 2: prefix from ind2 (mother), suffix from ind1 (father) ---
        prefix2 = list(orig2[:q])
        taken2 = set(prefix2)
        suffix2 = [gene for gene in orig1 if gene not in taken2]
        ind2[:] = prefix2 + suffix2

        return ind1, ind2

    @staticmethod
    def _crossover_two_point(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        Two-point crossover for precedence-feasible activity lists.

        Algorithm (Pseudocode: OP_TwoPoint_Crossover):
        ------------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw two random cut points 1 ≤ q1 < q2 < N.
        2. Child 1 inherits fixed positions from mother:
               C[1..q1]   := λᴹ[1..q1]
               C[q2+1..N] := λᴹ[q2+1..N]
        3. The middle segment (q1+1..q2) is filled by scanning the father
           left-to-right and inserting activities not already fixed in C,
           in order, into the available middle slots.
        4. Child 2 is built symmetrically (mother and father roles swapped).

        Precedence feasibility is preserved by the same argument as the
        one-point operator: the fixed prefix and suffix come from a feasible
        list, and the middle segment respects the relative order of the father.

        Example (q1=2, q2=4, N=6):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            fixed from mother: [1, 3, _, _, 4, 6]   (positions 1-2 and 5-6)
            middle from father (not in {1,3,4,6}): [2, 5]
            λᶜ = [1, 3, 2, 5, 4, 6]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 3:
            return ind1, ind2

        # Choose 1 ≤ q1 < q2 ≤ n-1 (Python slice points); guarantees
        # non-empty fixed ends and a non-empty middle segment.
        q1, q2 = sorted(random.sample(range(1, n), 2))

        # Save originals so Child 2 reads unmodified parent data.
        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: fixed from mother (orig1), middle from father (orig2) ---
        fixed1 = set(orig1[:q1]) | set(orig1[q2:])
        middle1 = [gene for gene in orig2 if gene not in fixed1]
        ind1[:] = orig1[:q1] + middle1 + orig1[q2:]

        # --- Child 2: fixed from father (orig2), middle from mother (orig1) ---
        fixed2 = set(orig2[:q1]) | set(orig2[q2:])
        middle2 = [gene for gene in orig1 if gene not in fixed2]
        ind2[:] = orig2[:q1] + middle2 + orig2[q2:]

        return ind1, ind2

    @staticmethod
    def _crossover_uniform_order(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        Uniform order-preserving crossover (UOX) for activity lists.

        Algorithm (Pseudocode: Uniform_Order_Crossover):
        -------------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw a random binary mask p ∈ {0,1}ᴺ.
        2. Initialise child C with empty slots.
        3. For each position i: if p[i]=1, set C[i] := λᴹ[i].
        4. Fill the remaining empty slots by scanning λᶠ left-to-right
           and placing each not-yet-used activity into the next empty slot.
        5. Child 2 is built symmetrically (mother and father roles swapped,
           same mask).

        The operator preserves precedence feasibility: masked positions copy a
        contiguous sub-sequence from the mother in its original order, and the
        father scan respects the father's (feasible) relative order for the
        remaining activities.

        Example (p=[1,0,1,0,0,1], N=6):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            After mask: C = [1, _, 2, _, _, 6]   (from mother at positions 0,2,5)
            Father scan (skip 1,2,6): 4, 3, 5
            λᶜ = [1, 4, 2, 3, 5, 6]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 2:
            return ind1, ind2

        mask = [random.randint(0, 1) for _ in range(n)]

        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: masked positions from mother (orig1), gaps from father (orig2) ---
        child1 = [None] * n
        used1: set = set()
        for i in range(n):
            if mask[i]:
                child1[i] = orig1[i]
                used1.add(orig1[i])
        fill1 = iter(gene for gene in orig2 if gene not in used1)
        ind1[:] = [child1[i] if child1[i] is not None else next(fill1) for i in range(n)]

        # --- Child 2: masked positions from father (orig2), gaps from mother (orig1) ---
        child2 = [None] * n
        used2: set = set()
        for i in range(n):
            if mask[i]:
                child2[i] = orig2[i]
                used2.add(orig2[i])
        fill2 = iter(gene for gene in orig1 if gene not in used2)
        ind2[:] = [child2[i] if child2[i] is not None else next(fill2) for i in range(n)]

        return ind1, ind2

    # ---------------------------------------------------------------------- #
    # Mutation — swap with topological repair                                  #
    # ---------------------------------------------------------------------- #

    def _mutate_swap(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Swap mutation with topological repair via ``reorder_by_dependencies``.

        Algorithm
        ---------
        1. Choose two distinct positions i and j uniformly at random.
        2. Swap the activity indices at those positions (may violate precedence).
        3. Convert the perturbed chromosome to ``(Activity, rank)`` pairs where
           rank = position index in the perturbed ordering.
        4. Call ``pert.reorder_by_dependencies(ranked, pert.forwardDict)`` which
           performs a lexicographic topological sort that keeps the perturbed
           order intact wherever it is already feasible and makes the minimum
           adjustment where it is not.
        5. Map the repaired activity sequence back to integer indices.

        The operator modifies ``individual`` **in place** per DEAP convention.

        The first and last positions (dummy START / END activities) are never
        selected, so the swap always targets real activities only.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 4:  # need at least 2 non-dummy positions in range(1, n-1)
            return (individual,)

        i, j = random.sample(range(1, n - 1), 2)
        individual[i], individual[j] = individual[j], individual[i]

        # Build (Activity, rank) pairs from the perturbed ordering.
        # rank = position index so reorder_by_dependencies preserves the swap
        # wherever precedence allows it.
        individual[:] = self._repair_chromosome(individual)
        return (individual,)

    def _mutate_adjacent_swap(
        self, individual: List[int], pmutation: float = 0.5
    ) -> Tuple[List[int]]:
        """
        Adjacent-swap mutation with precedence feasibility check.

        Algorithm (Pseudocode: Adjacent_Swap_Precedence_Mutation):
        -----------------------------------------------------------
        For each adjacent pair (i, i+1) in 1..N-1:
          1. With probability ``pmutation``, attempt to swap positions i and i+1.
          2. Accept the swap only if the result remains precedence-feasible.

        Feasibility of an adjacent swap is cheap to check: only the two
        swapped activities can violate precedence against each other.  Let
        ``a = individual[i]`` and ``b = individual[i+1]``.  After the swap,
        ``b`` sits before ``a``.  This is infeasible iff ``a`` is a
        predecessor of ``b`` (i.e. ``a ∈ backwardDict[b]``).  All other
        relative orders are unchanged, so no further check is needed.

        Unlike ``_mutate_swap``, no topological repair step is required: the
        swap is simply rejected when it would violate precedence, keeping the
        chromosome always valid without post-processing.

        The first and last positions (dummy START / END activities) are never
        involved in any swap attempt.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.
            Modified **in place** per DEAP convention.
        pmutation : float, optional
            Per-adjacent-pair swap probability.  Default ``0.5``.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 4:  # need at least two non-dummy interior positions
            return (individual,)

        backward = self.pert.backwardDict

        # range(1, n-2): pairs (1,2) … (n-3, n-2) — never touches position 0 or n-1.
        for i in range(1, n - 2):
            if random.random() >= pmutation:
                continue
            act_i  = self._activities[individual[i]]
            act_i1 = self._activities[individual[i + 1]]
            # Swap is feasible iff act_i is NOT a required predecessor of act_i1.
            if act_i not in backward.get(act_i1, []):
                individual[i], individual[i + 1] = individual[i + 1], individual[i]

        return (individual,)

    def _mutate_insertion_window(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Precedence-window insertion mutation.

        Algorithm (Pseudocode: Precedence_Window_Insertion_Mutation):
        --------------------------------------------------------------
        1. Choose a random non-dummy activity ``a`` from the chromosome.
        2. Compute the feasible insertion window [lo..hi] from the current
           positions of ``a``'s predecessors and successors:
               lo = 1 + max position of predecessors of a   (0 if no predecessors)
               hi = -1 + min position of successors of a   (n-1 if no successors)
        3. Draw ``new_pos`` uniformly from [lo..hi].
        4. Remove ``a`` from its current position and insert at ``new_pos``.

        The result is precedence-feasible by construction: lo and hi are
        chosen so that every predecessor of ``a`` still sits before ``new_pos``
        and every successor still sits after it.  No repair step is needed.

        Non-dummy activities are those whose name is neither ``START`` nor
        ``END`` (case-insensitive), matching ``pert.startActivity`` /
        ``pert.endActivity``.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.
            Modified **in place** per DEAP convention.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 2:
            return (individual,)

        # Indices of dummy (START / END) activities to exclude from selection.
        dummy_acts = {self.pert.startActivity, self.pert.endActivity} - {None}
        dummy_idx = {self._act_to_idx[a] for a in dummy_acts if a in self._act_to_idx}

        non_dummy_positions = [p for p in range(n) if individual[p] not in dummy_idx]
        if not non_dummy_positions:
            return (individual,)

        # Choose a random non-dummy position and resolve its Activity.
        cur_pos = random.choice(non_dummy_positions)
        act = self._activities[individual[cur_pos]]

        # Position lookup: gene value → index in chromosome (built once per call).
        pos_of = {individual[p]: p for p in range(n)}

        # lo: one past the rightmost predecessor's position.
        preds = self.pert.backwardDict.get(act, [])
        lo = (max(pos_of[self._act_to_idx[pr]] for pr in preds) + 1) if preds else 0

        # hi: one before the leftmost successor's position.
        succs = self.pert.forwardDict.get(act, [])
        hi = (min(pos_of[self._act_to_idx[sc]] for sc in succs) - 1) if succs else n - 1

        # Safety: current position must lie in [lo..hi] for a valid chromosome.
        if lo > hi:
            return (individual,)

        new_pos = random.randint(lo, hi)

        if new_pos == cur_pos:
            return (individual,)

        # Remove then re-insert; adjust index because removal shortens the list.
        gene = individual.pop(cur_pos)
        individual.insert(new_pos if new_pos < cur_pos else new_pos - 1, gene)

        return (individual,)

    def _mutate_consensus_reorder(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Consensus-guided block reorder mutation.

        The operator perturbs a local window of the chromosome using a
        consensus ranking induced by several reference orderings. This follows
        the spirit of consensus recombination: preserve agreements that recur
        across multiple good precedence-feasible schedules, but apply them as
        a unary mutation to a single individual.

        Algorithm
        ---------
        1. Select a random interior window [lo..hi] of non-dummy genes.
        2. Sample a small number of precedence-feasible reference orderings
           from the consensus library.
        3. For each gene in the window, compute its average position across
           the sampled references.
        4. Reorder only the genes inside the window by that consensus score,
           breaking ties by the current order.
        5. Apply topological repair to restore precedence feasibility if the
           local reorder conflicts with dependency constraints.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 6 or not self._consensus_position_maps:
            return (individual,)

        interior_positions = list(range(1, n - 1))
        if len(interior_positions) < 3:
            return (individual,)

        max_window = min(8, len(interior_positions))
        window_len = random.randint(3, max_window)
        lo = random.randint(1, n - 1 - window_len)
        hi = lo + window_len

        current_window = individual[lo:hi]
        current_rank = {gene: offset for offset, gene in enumerate(current_window)}

        sample_size = min(5, len(self._consensus_position_maps))
        sampled_maps = random.sample(self._consensus_position_maps, sample_size)

        def consensus_score(gene: int) -> Tuple[float, int]:
            avg_pos = sum(pos_map[gene] for pos_map in sampled_maps) / sample_size
            return avg_pos, current_rank[gene]

        reordered_window = sorted(current_window, key=consensus_score)
        if reordered_window == current_window:
            return (individual,)

        individual[lo:hi] = reordered_window
        individual[:] = self._repair_chromosome(individual)
        return (individual,)

    # ---------------------------------------------------------------------- #
    # Main optimisation loop                                                   #
    # ---------------------------------------------------------------------- #

    def run(self) -> Tuple[tools.HallOfFame, tools.Logbook]:
        """
        Execute the genetic algorithm.

        Workflow
        --------
        1. Generate initial population (priority-rule seeding + random fill).
        2. Evaluate fitness for every individual in generation 0.
        3. For each of ``n_gen`` generations:
           a. Tournament selection.
           b. Pairwise crossover with probability ``cxpb``.
           c. Apply the configured mutation operator with probability ``mutpb``.
           d. Re-evaluate invalidated offspring.
           d. Generational replacement.
           e. Update Hall of Fame and statistics logbook.

        Returns
        -------
        hof : deap.tools.HallOfFame
            Top ``hof_size`` individuals found across all generations.
        log : deap.tools.Logbook
            Per-generation statistics:
            ``gen``, ``nevals``, ``min``, ``avg``, ``std``, ``max``.
        """
        # ── Generation 0 ─────────────────────────────────────────────────────
        pop = self.generate_initial_population()
        if not pop:
            raise RuntimeError("Initial population is empty; GA cannot run.")

        fitnesses = list(map(self.toolbox.evaluate, pop))
        for ind, fit in zip(pop, fitnesses):
            ind.fitness.values = fit

        hof = tools.HallOfFame(self.hof_size)
        stats = tools.Statistics(lambda ind: ind.fitness.values[0])
        stats.register("min", np.min)
        stats.register("avg", np.mean)
        stats.register("std", np.std)
        stats.register("max", np.max)

        log = tools.Logbook()
        log.header = ["gen", "nevals"] + stats.fields
        hof.update(pop)
        record = stats.compile(pop)
        log.record(gen=0, nevals=len(pop), **record)
        if self.verbose:
            print(log.stream)

        # ── Generational loop ─────────────────────────────────────────────────
        for gen in range(1, self.n_gen + 1):
            # Selection
            offspring = list(
                map(self.toolbox.clone, self.toolbox.select(pop, len(pop)))
            )

            # Crossover
            for child1, child2 in zip(offspring[::2], offspring[1::2]):
                if random.random() < self.cxpb:
                    self.toolbox.mate(child1, child2)
                    del child1.fitness.values
                    del child2.fitness.values

            # Mutation
            for mutant in offspring:
                if random.random() < self.mutpb:
                    self.toolbox.mutate(mutant)
                    del mutant.fitness.values

            # Evaluate invalidated individuals
            invalid = [ind for ind in offspring if not ind.fitness.valid]
            for ind, fit in zip(invalid, map(self.toolbox.evaluate, invalid)):
                ind.fitness.values = fit

            # Generational replacement
            pop[:] = offspring
            hof.update(pop)

            record = stats.compile(pop)
            log.record(gen=gen, nevals=len(invalid), **record)
            if self.verbose:
                print(log.stream)

        logger.info(
            "GA finished | best = %.2f h | generations = %d | pop_size = %d",
            hof[0].fitness.values[0],
            self.n_gen,
            self.pop_size,
        )
        return hof, log

