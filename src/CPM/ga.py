    def _reset_run_counters(self) -> None:
        """Reset counters used by optional stopping criteria."""
        self.stop_reason = None
        self._eval_count = 0
        self._unique_schedule_signatures = set()
        self._track_unique_schedules = self.max_unique_schedules is not None

    def _schedule_signature(self) -> Tuple[Tuple[int, Optional[float]], ...]:
        """
        Canonical start-time signature for the schedule left by the SGS decoder.

        Two chromosomes can decode to the same start-time schedule.  The
        optional ``max_unique_schedules`` stopping rule follows that schedule
        space rather than raw chromosome count.
        """
        project_start = getattr(self.pert, 'startTime', None)
        signature: List[Tuple[int, Optional[float]]] = []
        for idx, act in enumerate(self._activities):
            start_time = getattr(act, 'startTime', None)
            if project_start is None or start_time is None:
                offset = None
            else:
                offset = round(
                    (start_time - project_start).total_seconds() / 3600.0,
                    9,
                )
            signature.append((idx, offset))
        return tuple(signature)

    def _note_fitness_evaluation(self) -> None:
        """Update evaluation and unique-schedule counters after SGS decoding."""
        self._eval_count += 1
        if self._track_unique_schedules:
            self._unique_schedule_signatures.add(self._schedule_signature())

    def _unique_schedule_count(self) -> int:
        """Number of unique decoded schedules tracked in this run."""
        return len(self._unique_schedule_signatures)

    def _evaluate(self, individual: List[int]) -> Tuple[float, ...]:
        """
        Decode an activity list chromosome and evaluate fitness using the
        Serial SGS.

        The chromosome (index permutation) is converted to an ordered list of
        ``Activity`` objects and passed to
        ``pert.calculateSerialScheduleWithResources(_ordered=...)`` which
        schedules each activity at the earliest feasible time consistent with
        the given ordering, precedence constraints, and resource/equipment/
        location capacity.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.

        Returns
        -------
        tuple of float
            ``(scheduled_duration - 2,)`` — single-objective minimisation.
        """
        ordered_acts = self._chromosome_to_activities(individual)
        out = self.pert.calculateSerialScheduleWithResources(_ordered=ordered_acts)
        self._note_fitness_evaluation()
        return (out['scheduled_duration'] - 2,)

    # ---------------------------------------------------------------------- #
    # Crossover — Hartmann (1998) one-point crossover for activity lists       #
    # ---------------------------------------------------------------------- #

    @staticmethod
    def _crossover_one_point(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        One-point crossover for precedence-feasible activity lists.

        Algorithm (Hartmann 1998, Section 4.2.1):
        ------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw a random cut point q with 1 ≤ q < N.
        2. Child 1 inherits positions 1..q from the mother.
        3. The remaining positions of Child 1 are filled by scanning the
           father left-to-right and appending each activity not already
           present in the child.
        4. Child 2 is built symmetrically (mother and father roles swapped).

        Hartmann (1998) proves that when both parents are precedence-feasible
        the child produced by this operator is also precedence-feasible,
        because:
        - The prefix is directly taken from a feasible list ⇒ each of those
          activities has all its predecessors before it.
        - The suffix preserves the relative order of the father, which is
          itself feasible, and only activities whose predecessors are already
          covered by the prefix are pulled in from that relative order first.

        Example (paper, p. 11, q = 3):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            λᶜ = [1, 3, 2, 4, 6, 5]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 2:
            return ind1, ind2

        q = random.randint(1, n - 1)

        # Save originals so Child 2 reads the unmodified first parent.
        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: prefix from ind1 (mother), suffix from ind2 (father) ---
        prefix1 = list(orig1[:q])
        taken1 = set(prefix1)
        suffix1 = [gene for gene in orig2 if gene not in taken1]
        ind1[:] = prefix1 + suffix1

        # --- Child 2: prefix from ind2 (mother), suffix from ind1 (father) ---
        prefix2 = list(orig2[:q])
        taken2 = set(prefix2)
        suffix2 = [gene for gene in orig1 if gene not in taken2]
        ind2[:] = prefix2 + suffix2

        return ind1, ind2

    @staticmethod
    def _crossover_two_point(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        Two-point crossover for precedence-feasible activity lists.

        Algorithm (Pseudocode: OP_TwoPoint_Crossover):
        ------------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw two random cut points 1 ≤ q1 < q2 < N.
        2. Child 1 inherits fixed positions from mother:
               C[1..q1]   := λᴹ[1..q1]
               C[q2+1..N] := λᴹ[q2+1..N]
        3. The middle segment (q1+1..q2) is filled by scanning the father
           left-to-right and inserting activities not already fixed in C,
           in order, into the available middle slots.
        4. Child 2 is built symmetrically (mother and father roles swapped).

        Precedence feasibility is preserved by the same argument as the
        one-point operator: the fixed prefix and suffix come from a feasible
        list, and the middle segment respects the relative order of the father.

        Example (q1=2, q2=4, N=6):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            fixed from mother: [1, 3, _, _, 4, 6]   (positions 1-2 and 5-6)
            middle from father (not in {1,3,4,6}): [2, 5]
            λᶜ = [1, 3, 2, 5, 4, 6]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 3:
            return ind1, ind2

        # Choose 1 ≤ q1 < q2 ≤ n-1 (Python slice points); guarantees
        # non-empty fixed ends and a non-empty middle segment.
        q1, q2 = sorted(random.sample(range(1, n), 2))

        # Save originals so Child 2 reads unmodified parent data.
        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: fixed from mother (orig1), middle from father (orig2) ---
        fixed1 = set(orig1[:q1]) | set(orig1[q2:])
        middle1 = [gene for gene in orig2 if gene not in fixed1]
        ind1[:] = orig1[:q1] + middle1 + orig1[q2:]

        # --- Child 2: fixed from father (orig2), middle from mother (orig1) ---
        fixed2 = set(orig2[:q1]) | set(orig2[q2:])
        middle2 = [gene for gene in orig1 if gene not in fixed2]
        ind2[:] = orig2[:q1] + middle2 + orig2[q2:]

        return ind1, ind2

    @staticmethod
    def _crossover_uniform_order(
        ind1: List[int], ind2: List[int]
    ) -> Tuple[List[int], List[int]]:
        """
        Uniform order-preserving crossover (UOX) for activity lists.

        Algorithm (Pseudocode: Uniform_Order_Crossover):
        -------------------------------------------------
        Given mother λᴹ (``ind1``) and father λᶠ (``ind2``):

        1. Draw a random binary mask p ∈ {0,1}ᴺ.
        2. Initialise child C with empty slots.
        3. For each position i: if p[i]=1, set C[i] := λᴹ[i].
        4. Fill the remaining empty slots by scanning λᶠ left-to-right
           and placing each not-yet-used activity into the next empty slot.
        5. Child 2 is built symmetrically (mother and father roles swapped,
           same mask).

        The operator preserves precedence feasibility: masked positions copy a
        contiguous sub-sequence from the mother in its original order, and the
        father scan respects the father's (feasible) relative order for the
        remaining activities.

        Example (p=[1,0,1,0,0,1], N=6):
            λᴹ = [1, 3, 2, 5, 4, 6]
            λᶠ = [2, 4, 6, 1, 3, 5]
            After mask: C = [1, _, 2, _, _, 6]   (from mother at positions 0,2,5)
            Father scan (skip 1,2,6): 4, 3, 5
            λᶜ = [1, 4, 2, 3, 5, 6]

        Parameters
        ----------
        ind1, ind2 : list of int
            Parent chromosomes.  Modified **in place** per DEAP convention.

        Returns
        -------
        (ind1, ind2) : modified children
        """
        n = len(ind1)
        if n < 2:
            return ind1, ind2

        mask = [random.randint(0, 1) for _ in range(n)]

        orig1 = list(ind1)
        orig2 = list(ind2)

        # --- Child 1: masked positions from mother (orig1), gaps from father (orig2) ---
        child1 = [None] * n
        used1: set = set()
        for i in range(n):
            if mask[i]:
                child1[i] = orig1[i]
                used1.add(orig1[i])
        fill1 = iter(gene for gene in orig2 if gene not in used1)
        ind1[:] = [child1[i] if child1[i] is not None else next(fill1) for i in range(n)]

        # --- Child 2: masked positions from father (orig2), gaps from mother (orig1) ---
        child2 = [None] * n
        used2: set = set()
        for i in range(n):
            if mask[i]:
                child2[i] = orig2[i]
                used2.add(orig2[i])
        fill2 = iter(gene for gene in orig1 if gene not in used2)
        ind2[:] = [child2[i] if child2[i] is not None else next(fill2) for i in range(n)]

        return ind1, ind2

    def _decuple_inner_crossover(
        self,
        parent1: List[int],
        parent2: List[int],
    ) -> Tuple[List[int], List[int]]:
        """
        Return two RCPSP-safe children for one DCS recombination edge.

        The DCS paper defines a hierarchy around a standard crossover operator.
        For this RCPSP adaptation, the inner operator is the existing uniform
        order-preserving crossover for activity-list chromosomes.
        """
        child1 = list(parent1)
        child2 = list(parent2)
        self._crossover_uniform_order(child1, child2)
        return child1, child2

    @staticmethod
    def _chromosome_diversity_distance(
        chromosome1: List[int],
        chromosome2: List[int],
    ) -> int:
        """Return positional diversity between two activity-list chromosomes."""
        return (
            sum(gene1 != gene2 for gene1, gene2 in zip(chromosome1, chromosome2))
            + abs(len(chromosome1) - len(chromosome2))
        )

    def _select_best_decuple_candidates(
        self,
        candidates: List[List[int]],
    ) -> List[List[int]]:
        """
        Return the two most mutually diverse DCS candidates without decoding.

        Diversity is measured as positional Hamming distance between activity
        lists.  Exact duplicate chromosomes are collapsed before selection.  If
        multiple pairs have the same mutual distance, prefer the pair with the
        larger total distance to the whole unique candidate pool, then the
        earliest generated pair for deterministic tie-breaking.
        """
        unique: List[Tuple[int, List[int]]] = []
        seen: set[Tuple[int, ...]] = set()
        for i, chromosome in enumerate(candidates):
            key = tuple(chromosome)
            if key in seen:
                continue
            unique.append((i, list(chromosome)))
            seen.add(key)

        if len(unique) <= 2:
            return [chromosome for _, chromosome in unique]

        pool_diversity: List[int] = []
        for i, (_, chromosome) in enumerate(unique):
            pool_diversity.append(
                sum(
                    self._chromosome_diversity_distance(chromosome, other)
                    for j, (_, other) in enumerate(unique)
                    if i != j
                )
            )

        best_pair: Optional[Tuple[int, int]] = None
        best_key: Optional[Tuple[int, int, int, int]] = None
        for i in range(len(unique) - 1):
            idx_i, chromosome_i = unique[i]
            for j in range(i + 1, len(unique)):
                idx_j, chromosome_j = unique[j]
                distance = self._chromosome_diversity_distance(
                    chromosome_i,
                    chromosome_j,
                )
                tie_key = (
                    distance,
                    pool_diversity[i] + pool_diversity[j],
                    -idx_i,
                    -idx_j,
                )
                if best_key is None or tie_key > best_key:
                    best_key = tie_key
                    best_pair = (i, j)

        if best_pair is None:
            return []

        return [
            list(unique[best_pair[0]][1]),
            list(unique[best_pair[1]][1]),
        ]

    def _crossover_decuple(
        self,
        ind1: List[int],
        ind2: List[int],
    ) -> Tuple[List[int], List[int]]:
        """
        Decuple Crossover Scheme (DCS), adapted to RCPSP activity lists.

        DCS generates ten offspring for one parent pair:

        1. ``P1 x P2`` produces initial children ``Ch1`` and ``Ch2``.
        2. ``Ch1`` is recombined with ``P1`` and ``P2``.
        3. ``Ch2`` is recombined with ``P1`` and ``P2``.
        4. The two most mutually diverse candidates replace ``ind1`` and
           ``ind2``.  Fitness evaluation is left to the normal invalid-offspring
           evaluation path.
        """
        if len(ind1) < 2:
            candidates = [list(ind1), list(ind2)]
        else:
            parent1 = list(ind1)
            parent2 = list(ind2)
            ch1, ch2 = self._decuple_inner_crossover(parent1, parent2)

            candidates = [ch1, ch2]
            for initial_child in (ch1, ch2):
                for parent in (parent1, parent2):
                    c1, c2 = self._decuple_inner_crossover(initial_child, parent)
                    candidates.extend([c1, c2])

        selected = self._select_best_decuple_candidates(candidates)
        if len(selected) < 2:
            return ind1, ind2

        child1, child2 = selected[:2]
        ind1[:] = child1
        ind2[:] = child2

        return ind1, ind2

    # ---------------------------------------------------------------------- #
    # Mutation — swap with topological repair                                  #
    # ---------------------------------------------------------------------- #

    def _mutate_swap(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Swap mutation with topological repair via ``reorder_by_dependencies``.

        Algorithm
        ---------
        1. Choose two distinct positions i and j uniformly at random.
        2. Swap the activity indices at those positions (may violate precedence).
        3. Convert the perturbed chromosome to ``(Activity, rank)`` pairs where
           rank = position index in the perturbed ordering.
        4. Call ``pert.reorder_by_dependencies(ranked, pert.forwardDict)`` which
           performs a lexicographic topological sort that keeps the perturbed
           order intact wherever it is already feasible and makes the minimum
           adjustment where it is not.
        5. Map the repaired activity sequence back to integer indices.

        The operator modifies ``individual`` **in place** per DEAP convention.

        The first and last positions (dummy START / END activities) are never
        selected, so the swap always targets real activities only.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 4:  # need at least 2 non-dummy positions in range(1, n-1)
            return (individual,)

        i, j = random.sample(range(1, n - 1), 2)
        individual[i], individual[j] = individual[j], individual[i]

        # Build (Activity, rank) pairs from the perturbed ordering.
        # rank = position index so reorder_by_dependencies preserves the swap
        # wherever precedence allows it.
        individual[:] = self._repair_chromosome(individual)
        return (individual,)

    def _mutate_adjacent_swap(
        self, individual: List[int], pmutation: float = 0.5
    ) -> Tuple[List[int]]:
        """
        Adjacent-swap mutation with precedence feasibility check.

        Algorithm (Pseudocode: Adjacent_Swap_Precedence_Mutation):
        -----------------------------------------------------------
        For each adjacent pair (i, i+1) in 1..N-1:
          1. With probability ``pmutation``, attempt to swap positions i and i+1.
          2. Accept the swap only if the result remains precedence-feasible.

        Feasibility of an adjacent swap is cheap to check: only the two
        swapped activities can violate precedence against each other.  Let
        ``a = individual[i]`` and ``b = individual[i+1]``.  After the swap,
        ``b`` sits before ``a``.  This is infeasible iff ``a`` is a
        predecessor of ``b`` (i.e. ``a ∈ backwardDict[b]``).  All other
        relative orders are unchanged, so no further check is needed.

        Unlike ``_mutate_swap``, no topological repair step is required: the
        swap is simply rejected when it would violate precedence, keeping the
        chromosome always valid without post-processing.

        The first and last positions (dummy START / END activities) are never
        involved in any swap attempt.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.
            Modified **in place** per DEAP convention.
        pmutation : float, optional
            Per-adjacent-pair swap probability.  Default ``0.5``.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 4:  # need at least two non-dummy interior positions
            return (individual,)

        backward = self.pert.backwardDict

        # range(1, n-2): pairs (1,2) … (n-3, n-2) — never touches position 0 or n-1.
        for i in range(1, n - 2):
            if random.random() >= pmutation:
                continue
            act_i  = self._activities[individual[i]]
            act_i1 = self._activities[individual[i + 1]]
            # Swap is feasible iff act_i is NOT a required predecessor of act_i1.
            if act_i not in backward.get(act_i1, []):
                individual[i], individual[i + 1] = individual[i + 1], individual[i]

        return (individual,)

    def _mutate_insertion_window(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Precedence-window insertion mutation.

        Algorithm (Pseudocode: Precedence_Window_Insertion_Mutation):
        --------------------------------------------------------------
        1. Choose a random non-dummy activity ``a`` from the chromosome.
        2. Compute the feasible insertion window [lo..hi] from the current
           positions of ``a``'s predecessors and successors:
               lo = 1 + max position of predecessors of a   (0 if no predecessors)
               hi = -1 + min position of successors of a   (n-1 if no successors)
        3. Draw ``new_pos`` uniformly from [lo..hi].
        4. Remove ``a`` from its current position and insert at ``new_pos``.

        The result is precedence-feasible by construction: lo and hi are
        chosen so that every predecessor of ``a`` still sits before ``new_pos``
        and every successor still sits after it.  No repair step is needed.

        Non-dummy activities are those whose name is neither ``START`` nor
        ``END`` (case-insensitive), matching ``pert.startActivity`` /
        ``pert.endActivity``.

        Parameters
        ----------
        individual : list of int
            Precedence-feasible permutation of activity indices.
            Modified **in place** per DEAP convention.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 2:
            return (individual,)

        # Indices of dummy (START / END) activities to exclude from selection.
        dummy_acts = {self.pert.startActivity, self.pert.endActivity} - {None}
        dummy_idx = {self._act_to_idx[a] for a in dummy_acts if a in self._act_to_idx}

        non_dummy_positions = [p for p in range(n) if individual[p] not in dummy_idx]
        if not non_dummy_positions:
            return (individual,)

        # Choose a random non-dummy position and resolve its Activity.
        cur_pos = random.choice(non_dummy_positions)
        act = self._activities[individual[cur_pos]]

        # Position lookup: gene value → index in chromosome (built once per call).
        pos_of = {individual[p]: p for p in range(n)}

        # lo: one past the rightmost predecessor's position.
        preds = self.pert.backwardDict.get(act, [])
        lo = (max(pos_of[self._act_to_idx[pr]] for pr in preds) + 1) if preds else 0

        # hi: one before the leftmost successor's position.
        succs = self.pert.forwardDict.get(act, [])
        hi = (min(pos_of[self._act_to_idx[sc]] for sc in succs) - 1) if succs else n - 1

        # Safety: current position must lie in [lo..hi] for a valid chromosome.
        if lo > hi:
            return (individual,)

        new_pos = random.randint(lo, hi)

        if new_pos == cur_pos:
            return (individual,)

        # Remove then re-insert; adjust index because removal shortens the list.
        gene = individual.pop(cur_pos)
        individual.insert(new_pos if new_pos < cur_pos else new_pos - 1, gene)

        return (individual,)

    def _mutate_consensus_reorder(self, individual: List[int]) -> Tuple[List[int]]:
        """
        Consensus-guided block reorder mutation.

        The operator perturbs a local window of the chromosome using a
        consensus ranking induced by several reference orderings. This follows
        the spirit of consensus recombination: preserve agreements that recur
        across multiple good precedence-feasible schedules, but apply them as
        a unary mutation to a single individual.

        Algorithm
        ---------
        1. Select a random interior window [lo..hi] of non-dummy genes.
        2. Sample a small number of precedence-feasible reference orderings
           from the consensus library.
        3. For each gene in the window, compute its average position across
           the sampled references.
        4. Reorder only the genes inside the window by that consensus score,
           breaking ties by the current order.
        5. Apply topological repair to restore precedence feasibility if the
           local reorder conflicts with dependency constraints.

        Returns
        -------
        tuple
            ``(individual,)`` — single-element tuple per DEAP convention.
        """
        n = len(individual)
        if n < 6 or not self._consensus_position_maps:
            return (individual,)

        interior_positions = list(range(1, n - 1))
        if len(interior_positions) < 3:
            return (individual,)

        max_window = min(8, len(interior_positions))
        window_len = random.randint(3, max_window)
        lo = random.randint(1, n - 1 - window_len)
        hi = lo + window_len

        current_window = individual[lo:hi]
        current_rank = {gene: offset for offset, gene in enumerate(current_window)}

        sample_size = min(5, len(self._consensus_position_maps))
        sampled_maps = random.sample(self._consensus_position_maps, sample_size)

        def consensus_score(gene: int) -> Tuple[float, int]:
            avg_pos = sum(pos_map[gene] for pos_map in sampled_maps) / sample_size
            return avg_pos, current_rank[gene]

        reordered_window = sorted(current_window, key=consensus_score)
        if reordered_window == current_window:
            return (individual,)

        individual[lo:hi] = reordered_window
        individual[:] = self._repair_chromosome(individual)
        return (individual,)

    # ---------------------------------------------------------------------- #
    # Population replacement                                                    #
    # ---------------------------------------------------------------------- #

    @staticmethod
    def _fitness_value(individual: List[int]) -> float:
        """Return the scalar makespan fitness used by this single-objective GA."""
        return individual.fitness.values[0]

    def _select_diverse_elites(
        self,
        candidates: List[List[int]],
        k: int,
    ) -> List[List[int]]:
        """
        Select the best ``k`` candidates while preferring unique chromosomes.

        This is still elitist survivor selection, but it avoids filling the next
        generation with duplicate activity lists when crossover or repair creates
        identical chromosomes. If fewer than ``k`` unique chromosomes exist, the
        remaining slots are filled by normal fitness order.
        """
        ranked = sorted(candidates, key=self._fitness_value)
        selected: List[List[int]] = []
        selected_ids = set()
        seen_chromosomes = set()

        for individual in ranked:
            chromosome = tuple(individual)
            if chromosome in seen_chromosomes:
                continue
            selected.append(individual)
            selected_ids.add(id(individual))
            seen_chromosomes.add(chromosome)
            if len(selected) == k:
                return selected

        for individual in ranked:
            if id(individual) in selected_ids:
                continue
            selected.append(individual)
            if len(selected) == k:
                break

        return selected

    def _replace_population(
        self,
        parents: List[List[int]],
        offspring: List[List[int]],
    ) -> List[List[int]]:
        """
        Build the next generation using the configured survivor strategy.

        ``parents`` and ``offspring`` must already have valid fitness values.
        Lower fitness is better because the RCPSP objective is makespan
        minimisation.
        """
        target_size = len(parents)

        if self.replacement_strategy == 'generational':
            return list(offspring)

        if self.replacement_strategy == 'elitist':
            return tools.selBest(list(parents) + list(offspring), target_size)

        if self.replacement_strategy == 'steady_state':
            replace_count = min(
                target_size,
                max(1, math.ceil(target_size * self.replacement_fraction)),
            )
            keep_count = target_size - replace_count
            max_parent_keep = target_size - 1 if target_size > 1 else target_size
            keep_count = max(keep_count, min(self.elite_size, max_parent_keep))
            replace_count = target_size - keep_count

            survivors = tools.selBest(parents, keep_count)
            entrants = tools.selBest(offspring, replace_count)
            return survivors + entrants

        if self.replacement_strategy == 'diverse_elitist':
            return self._select_diverse_elites(
                list(parents) + list(offspring),
                target_size,
            )

        raise RuntimeError(f"Unsupported replacement_strategy: {self.replacement_strategy}")

    # ---------------------------------------------------------------------- #
    # Main optimisation loop                                                   #
    # ---------------------------------------------------------------------- #

    def _stopping_reason(
        self,
        best_fitness: float,
        stall: int,
        std_stall: int,
    ) -> Optional[str]:
        """Return the active stopping reason, if an optional criterion fired."""
        if self.target_fitness is not None and best_fitness <= self.target_fitness:
            return 'target_fitness'
        if (
            self.max_unique_schedules is not None
            and self._unique_schedule_count() >= self.max_unique_schedules
        ):
            return 'max_unique_schedules'
        if self.max_evals is not None and self._eval_count >= self.max_evals:
            return 'max_evals'
        if self.stall_generations is not None and stall >= self.stall_generations:
            return 'stall_generations'
        if self.fitness_std_tol is not None and std_stall >= self.std_generations:
            return 'fitness_std_tol'
        return None

    def run(self) -> Tuple[tools.HallOfFame, tools.Logbook]:
        """
        Execute the genetic algorithm.

        Workflow
        --------
        1. Generate initial population using ``initial_population_mode``.
        2. Evaluate fitness for every individual in generation 0.
        3. For each of ``n_gen`` generations:
           a. Tournament selection.
           b. Pairwise crossover with probability ``cxpb``.
           c. Apply the configured mutation operator with probability ``mutpb``.
           d. Re-evaluate invalidated offspring.
           e. Apply the configured population replacement strategy.
           f. Update Hall of Fame.
           g. Refresh the consensus library when ``consensus_reorder`` is active
              and the configured generation interval or improvement trigger fires.
           h. Update statistics logbook.

        Returns
        -------
        hof : deap.tools.HallOfFame
            Top ``hof_size`` individuals found across all generations.
            When ``fb_improvement=True`` the HoF individuals are polished
            by a final FBF pass before being returned.
        log : deap.tools.Logbook
            Per-generation statistics:
            ``gen``, ``nevals``, ``evals``, ``best``, ``stall``,
            ``unique_schedules``, ``stop_reason``, ``min``, ``avg``, ``std``,
            ``max``.
        """
        # ── Generation 0 ─────────────────────────────────────────────────────
        self._reset_run_counters()
        pop = self.generate_initial_population()
        if not pop:
            raise RuntimeError("Initial population is empty; GA cannot run.")

        fitnesses = list(map(self.toolbox.evaluate, pop))
        for ind, fit in zip(pop, fitnesses):
            ind.fitness.values = fit

        hof = tools.HallOfFame(self.hof_size)
        stats = tools.Statistics(lambda ind: ind.fitness.values[0])
        stats.register("min", np.min)
        stats.register("avg", np.mean)
        stats.register("std", np.std)
        stats.register("max", np.max)

        log = tools.Logbook()
        log.header = [
            "gen", "nevals", "evals", "best", "stall",
            "unique_schedules", "stop_reason",
        ] + stats.fields
        hof.update(pop)
        if self._consensus_updates_enabled():
            self.update_consensus_library(pop, hof)
        record = stats.compile(pop)
        best_ever = hof[0].fitness.values[0]
        stall = 0
        std_stall = (
            1
            if self.fitness_std_tol is not None
            and record['std'] <= self.fitness_std_tol
            else 0
        )
        stop_reason = self._stopping_reason(best_ever, stall, std_stall)
        log.record(
            gen=0,
            nevals=len(pop),
            evals=self._eval_count,
            best=best_ever,
            stall=stall,
            unique_schedules=self._unique_schedule_count(),
            stop_reason=stop_reason or '',
            **record,
        )
        if self.verbose:
            print(log.stream)

        # ── Generational loop ─────────────────────────────────────────────────
        if stop_reason is None:
            for gen in range(1, self.n_gen + 1):
                if self.max_evals is not None and self._eval_count >= self.max_evals:
                    stop_reason = 'max_evals'
                    break
                gen_eval_start = self._eval_count

                # Selection
                offspring = list(
                    map(self.toolbox.clone, self.toolbox.select(pop, len(pop)))
                )

                # Crossover
                for child1, child2 in zip(offspring[::2], offspring[1::2]):
                    if random.random() < self.cxpb:
                        self.toolbox.mate(child1, child2)
                        del child1.fitness.values
                        del child2.fitness.values

                # Mutation
                if stop_reason is None:
                    for mutant in offspring:
                        if random.random() < self.mutpb:
                            self.toolbox.mutate(mutant)
                            del mutant.fitness.values

                # Evaluate invalidated individuals
                invalid = [ind for ind in offspring if not ind.fitness.valid]
                if self.max_evals is not None:
                    remaining_evals = self.max_evals - self._eval_count
                    if len(invalid) > remaining_evals:
                        stop_reason = 'max_evals'
                        break
                for ind, fit in zip(invalid, map(self.toolbox.evaluate, invalid)):
                    ind.fitness.values = fit

                # Population replacement
                pop[:] = self._replace_population(pop, offspring)
                hof.update(pop)

                # Periodic FBF improvement (optional)
                if self.fb_improvement and self.fb_freq > 0 and gen % self.fb_freq == 0:
                    n_fb = self.apply_fb_improvement(pop)
                    hof.update(pop)
                    if self.verbose and n_fb:
                        print(
                            f"  [FBF gen {gen}] {n_fb}/{len(pop)} improved"
                            f" | best = {hof[0].fitness.values[0]:.2f} h"
                        )

                record = stats.compile(pop)
                gen_best = hof[0].fitness.values[0]
                best_improved = gen_best < best_ever - self.stall_tolerance
                if best_improved:
                    best_ever = gen_best
                    stall = 0
                else:
                    stall += 1

                if self._should_update_consensus_library(gen, best_improved):
                    n_refs = self.update_consensus_library(pop, hof)
                    if self.verbose:
                        reason = (
                            "new best"
                            if best_improved
                            else f"freq={self.consensus_update_freq}"
                        )
                        print(
                            f"  [Consensus gen {gen}] refreshed "
                            f"{n_refs} references ({reason})"
                        )

                if (
                    self.fitness_std_tol is not None
                    and record['std'] <= self.fitness_std_tol
                ):
                    std_stall += 1
                else:
                    std_stall = 0

                if stop_reason is None:
                    stop_reason = self._stopping_reason(best_ever, stall, std_stall)
                log.record(
                    gen=gen,
                    nevals=self._eval_count - gen_eval_start,
                    evals=self._eval_count,
                    best=best_ever,
                    stall=stall,
                    unique_schedules=self._unique_schedule_count(),
                    stop_reason=stop_reason or '',
                    **record,
                )
                if self.verbose:
                    print(log.stream)
                if stop_reason is not None:
                    break

        self.stop_reason = stop_reason or 'max_generations'
        if log:
            log[-1]['stop_reason'] = self.stop_reason

        # Final FBF polish on the full population; update HoF from result
        if self.fb_improvement:
            n_fb = self.apply_fb_improvement(pop)
            hof.update(pop)
            if self.verbose:
                msg = (
                    f"FBF final polish: {n_fb}/{len(pop)} improved"
                    f" | best = {hof[0].fitness.values[0]:.2f} h"
                )
                print(f"\n{msg}")
            logger.info(
                "FBF final polish: %d/%d improved | best = %.2f h",
                n_fb,
                len(pop),
                hof[0].fitness.values[0],
            )

        logger.info(
            "GA finished | best = %.2f h | generations = %d | population = %d",
            hof[0].fitness.values[0],
            self.n_gen,
            len(pop),
        )
        return hof, log

