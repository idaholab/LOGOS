"""
ga.py — Genetic Algorithm for Resource-Constrained Project Scheduling (RCPSP)

Implements the Activity List representation and one-point crossover operator
from Hartmann (1998) / Kolisch & Hartmann (1999), using DEAP as the GA engine.

References
----------
Kolisch, R. and Hartmann, S. (1999). Heuristic Algorithms for Solving the
Resource-Constrained Project Scheduling Problem: Classification and
Computational Analysis. In J. Weglarz (ed.), Project Scheduling: Recent
Models, Algorithms and Applications, 147-178. Kluwer.

Hartmann, S. (1998). A competitive genetic algorithm for resource-constrained
project scheduling. Naval Research Logistics.

Chromosome representation
-------------------------
A **precedence-feasible activity list**

    λ = [i₀, i₁, ..., i_{N-1}]

where each element is the index of an activity in ``pert.forwardDict`` (i.e.
``pert.forwardDict.keys()`` enumerated once at construction time).  Activity
at position g must have all its predecessors at earlier positions (precedence
feasibility).

``pert.priority_calculation()`` with ``reorder_by_dependencies()`` always
produces precedence-feasible orderings, so all chromosomes derived from named
priority rules are valid.  Random chromosomes are generated by calling the
same pipeline with ``priority_rule='random'``.

Decoding (fitness evaluation)
------------------------------
A chromosome is decoded by passing the corresponding ordered list of
``Activity`` objects to ``pert.calculateSerialScheduleWithResources()`` via
the ``_ordered`` keyword added in this release.  Fitness =
``out['scheduled_duration'] - 2`` (strips dummy start/end overhead).

Initial population
------------------
One individual per entry in ``PRIORITY_RULES`` is seeded using
``priority_calculation`` to build the ordering.  The schedule durations from
both serial SGS (``calculateSerialScheduleWithResources``) and parallel SGS
(``calculateScheduleWithResources(sgs='max_use_res_ranked')``) are recorded
for the same priority rule for benchmarking purposes only.  Remaining
population slots are filled with random precedence-feasible permutations.

Crossover — Hartmann (1998) one-point crossover for activity lists
------------------------------------------------------------------
Given mother λᴹ and father λᶠ and a random cut point q (1 ≤ q < N):

1. The first q positions of the child are taken directly from the mother.
2. The remaining N-q positions are filled by scanning the father from left
   to right and appending each activity not yet present in the child.

Hartmann (1998) proves that a child produced this way from two
precedence-feasible parents is itself precedence-feasible.

Two children are produced symmetrically (roles of mother and father swapped).

Mutation — swap mutation with topological repair
-------------------------------------------------
A single individual is mutated by:

1. Picking two random distinct positions i and j.
2. Swapping the activities at those positions (potentially violating
   precedence constraints).
3. Reconstructing ``(Activity, rank)`` pairs from the perturbed ordering
   (rank = position index).
4. Calling ``pert.reorder_by_dependencies(ranked, pert.forwardDict)`` which
   performs a lexicographic topological sort that preserves the perturbed
   order as closely as possible while restoring precedence feasibility.
5. Mapping the repaired activity sequence back to the index chromosome.

This keeps the swap when it is already feasible and makes the minimum
necessary adjustment when it is not, so the mutation injects genuine
diversity while always producing a valid chromosome.

Requirements
------------
    pip install deap
"""

